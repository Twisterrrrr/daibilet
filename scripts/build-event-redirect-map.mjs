#!/usr/bin/env node
/**
 * Build data/redirects/event-pdp-redirects.json from a GSC "not indexed" export
 * + live catalog. Matches by Event id (not slug), resolves the canonical EventPage
 * slug, validates, and writes with --apply. Dry-run by default.
 * Usage: node apps/web/node_modules/tsx/dist/cli.mjs scripts/build-event-redirect-map.mjs --gsc=file [--apply]
 * DB: EVENT_MAP_DATABASE_URL or DATABASE_URL.
 */
import { existsSync, readFileSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { resolveEventPageSlugsForEventIds } from '../apps/backend/src/public-event-page-links.ts';
import { validateEventRedirectMap } from '../apps/web/src/lib/event-redirect-map.ts';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { Pool } = createRequire(path.join(rootDir, 'packages', 'db', 'package.json'))('pg');

function loadRootEnv(projectRoot) {
  const envPath = path.join(projectRoot, '.env');
  if (!existsSync(envPath)) return;
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const sep = trimmed.indexOf('=');
    if (sep <= 0) continue;
    const key = trimmed.slice(0, sep).trim();
    const value = trimmed.slice(sep + 1).trim().replace(/^['"]|['"]$/g, '');
    if (key && process.env[key] == null) process.env[key] = value;
  }
}

/** Parse a GSC CSV/TSV dump into all daibilet.ru paths (deduped; header + non-URL rows dropped). */
export function extractDaibiletPaths(text) {
  const out = new Set();
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t) continue;
    const first = t.includes('\t') ? t.split('\t')[0] : t.split(',')[0];
    const url = first.replace(/^"|"$/g, '').trim();
    if (!url.startsWith('http')) continue;
    try { out.add(new URL(url).pathname); } catch { /* skip malformed */ }
  }
  return [...out];
}

/** Subset of extractDaibiletPaths limited to /events/ rows (the redirect-map scope). */
export function extractEventUrls(text) {
  return extractDaibiletPaths(text).filter((p) => p.startsWith('/events/'));
}

/** Stable identity + source kind from an /events/ path (id-based, not slug). */
export function identityFromEventPath(pathname) {
  let slug = pathname.slice('/events/'.length).split(/[?#]/u, 1)[0] || '';
  try { slug = decodeURIComponent(slug); } catch { /* keep raw */ }
  const lower = slug.toLowerCase();
  const tcHex = lower.match(/^(?:tc-)?([a-f\d]{24})(?:-|$)/iu)?.[1] || lower.match(/-([a-f\d]{24})$/iu)?.[1] || '';
  const tepNum = lower.match(/-(\d{2,6})$/iu)?.[1] || '';
  const internalId = tcHex ? `evt_${tcHex}` : tepNum ? `evt_tep_${tepNum}` : '';
  const kind = tcHex ? 'tc_code' : /[а-яё]/iu.test(slug) ? 'cyrillic' : 'legacy_slug';
  return { slug: lower, internalId, kind };
}

function cliArgs() {
  const args = {};
  for (const arg of process.argv.slice(2)) {
    const [k, ...p] = arg.replace(/^--/, '').split('=');
    args[k] = p.join('=') || true;
  }
  return args;
}

const ENTRIES_TS_PATH = path.join(rootDir, 'apps', 'web', 'src', 'lib', 'event-redirect-entries.ts');

function generateEventRedirectEntriesTs(map) {
  const lines = map.entries.map((entry) => (
    `  { sourcePath: ${JSON.stringify(entry.sourcePath)}, eventId: ${JSON.stringify(entry.eventId)}, kind: ${JSON.stringify(entry.kind)}, status: ${entry.status}, targetPath: ${JSON.stringify(entry.targetPath)} },`
  ));
  return [
    '// AUTO-GENERATED by scripts/build-event-redirect-map.mjs - do not edit by hand.',
    "import type { EventRedirectEntry } from './event-redirect-map';",
    '',
    'export const EVENT_REDIRECT_ENTRIES: EventRedirectEntry[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

/** Normalize an EventPageRoute.path (bare slug or /events/slug) to a sourcePath + slug. */
function normalizeEventPath(value) {
  let s = String(value || '').trim().replace(/\/+$/, '');
  if (s.startsWith('/events/')) return { sourcePath: s, slug: s.slice('/events/'.length) };
  s = s.replace(/^\//, '');
  return { sourcePath: `/events/${s}`, slug: s };
}

async function loadExistingEntries(outputPath) {
  try {
    const parsed = JSON.parse(await readFile(outputPath, 'utf8'));
    return parsed && Array.isArray(parsed.entries) ? parsed.entries : [];
  } catch {
    return [];
  }
}

function mergeEntries(existing, incoming) {
  const map = new Map();
  for (const e of existing) map.set(e.sourcePath, e);
  for (const e of incoming) map.set(e.sourcePath, e);
  return [...map.values()].sort((a, b) => a.sourcePath.localeCompare(b.sourcePath));
}

/** Union the new run into the existing map (incoming wins on conflict), then write both files. */
async function writeMergedMap(nextMap, outputPath) {
  const merged = mergeEntries(await loadExistingEntries(outputPath), nextMap.entries);
  const mergedMap = { version: 1, generatedAt: new Date().toISOString(), entries: merged };
  await writeFile(outputPath, `${JSON.stringify(mergedMap, null, 2)}\n`, 'utf8');
  await writeFile(ENTRIES_TS_PATH, generateEventRedirectEntriesTs(mergedMap), 'utf8');
  console.log(`Wrote redirect map (${mergedMap.entries.length} entries, merged) + ${ENTRIES_TS_PATH}`);
}

/**
 * Enumerate the complete 301 alias map from our own catalog (no GSC input):
 * 1. EventPageRoute (CANDIDATE/HISTORICAL/CURRENT) -> its published EventPage canonical.
 * 2. Direct EventPageEvent links where the Event slug differs from the canonical.
 * Read-only. 410 (dead slot URLs) remain GSC-driven because pre-merge slot slugs
 * are not reliably retained in the DB.
 */
async function runFromCatalog(connectionString, { apply, outputPath }) {
  const pool = new Pool({ connectionString, max: 1 });
  try {
    const client = await pool.connect();
    const entries = [];
    const seen = new Set();
    try {
      await client.query('BEGIN READ ONLY');

      const routes = await client.query(
        `SELECT route.path AS path, page.slug AS slug, route."eventPageId" AS "pageId"
         FROM "EventPageRoute" route
         JOIN "EventPage" page ON page.id = route."eventPageId"
         WHERE page.status = 'READY' AND page."publishedAt" IS NOT NULL
           AND route.kind IN ('CANDIDATE','HISTORICAL','CURRENT')`,
      );
      for (const row of routes.rows) {
        const { sourcePath, slug } = normalizeEventPath(row.path);
        const targetPath = `/events/${row.slug}`;
        if (!slug || slug === row.slug || sourcePath === targetPath || seen.has(sourcePath)) continue;
        seen.add(sourcePath);
        entries.push({ sourcePath, eventId: row.pageId, kind: 'legacy_slug', status: 301, targetPath });
      }

      const direct = await client.query(
        `SELECT lower(event.slug) AS slug, lower(page.slug) AS canonical, event.id AS "eventId"
         FROM "EventPageEvent" link
         JOIN "EventPage" page ON page.id = link."eventPageId"
         JOIN "Event" event ON event.id = link."eventId"
         WHERE page.status = 'READY' AND page."publishedAt" IS NOT NULL
           AND lower(coalesce(event.slug, '')) <> lower(page.slug)`,
      );
      for (const row of direct.rows) {
        const sourcePath = `/events/${row.slug}`;
        const targetPath = `/events/${row.canonical}`;
        if (!row.slug || sourcePath === targetPath || seen.has(sourcePath)) continue;
        seen.add(sourcePath);
        entries.push({ sourcePath, eventId: row.eventId, kind: 'legacy_slug', status: 301, targetPath });
      }

      await client.query('ROLLBACK');
    } finally {
      client.release();
    }

    const map = {
      version: 1,
      generatedAt: new Date().toISOString(),
      entries: entries.sort((a, b) => a.sourcePath.localeCompare(b.sourcePath)),
    };
    const errors = validateEventRedirectMap(map);
    const summary = {
      mode: apply ? 'apply' : 'dry-run',
      catalog301: map.entries.length,
      validationErrors: errors,
      outputPath,
    };
    if (errors.length) {
      console.log(JSON.stringify(summary, null, 2));
      console.error('Catalog map failed validation; nothing written.');
      process.exitCode = 1;
      return;
    }
    if (apply) {
      await writeMergedMap(map, outputPath);
    }
    console.log(JSON.stringify({ ...summary, preview: map.entries.slice(0, 5) }, null, 2));
    if (!apply) console.warn(`Dry-run: no write. Re-run with --apply to write ${outputPath}.`);
  } finally {
    await pool.end();
  }
}

async function main() {
  const args = cliArgs();
  const apply = Boolean(args.apply);
  const outputPath = typeof args.output === 'string' ? args.output : path.join(rootDir, 'data', 'redirects', 'event-pdp-redirects.json');
  loadRootEnv(rootDir);
  const connectionString = process.env.EVENT_MAP_DATABASE_URL || process.env.DATABASE_URL;
  if (!connectionString) {
    console.error('Set EVENT_MAP_DATABASE_URL or DATABASE_URL');
    process.exit(2);
  }

  if (args['from-catalog']) {
    await runFromCatalog(connectionString, { apply, outputPath });
    return;
  }

  if (typeof args.gsc !== 'string') {
    console.error('Usage: node apps/web/node_modules/tsx/dist/cli.mjs scripts/build-event-redirect-map.mjs --gsc=file|--from-catalog [--apply]');
    process.exit(2);
  }

  const allPaths = extractDaibiletPaths(await readFile(args.gsc, 'utf8'));
  const paths = allPaths.filter((p) => p.startsWith('/events/'));
  const nonEventPaths = allPaths.filter((p) => !p.startsWith('/events/'));
  if (!paths.length) { console.error('No /events/ URLs found'); process.exit(2); }
  console.log(`GSC URLs: ${allPaths.length} total, ${paths.length} events, ${nonEventPaths.length} non-events`);

  const records = paths.map((pathname) => ({ pathname, identity: identityFromEventPath(pathname) }));
  const internalIds = [...new Set(records.map((r) => r.identity.internalId).filter(Boolean))];
  const slugs = [...new Set(records.map((r) => r.identity.slug))];

  const pool = new Pool({ connectionString, max: 1 });
  try {
    const client = await pool.connect();
    const byId = new Map();
    const bySlug = new Map();
    try {
      await client.query('BEGIN READ ONLY');
      const result = await client.query(
        `SELECT e.id AS "eventId", lower(coalesce(e.slug, '')) AS "slug",
           COALESCE((SELECT count(*)::int FROM "EventSession" s
             WHERE s."eventId" = e.id AND s."isActive" IS TRUE AND s."cancelledAt" IS NULL
               AND s."archivedAt" IS NULL AND COALESCE(s."endsAt", s."startsAt") >= now()), 0) AS "futureSessionCount"
         FROM "Event" e
         WHERE lower(e.id) = ANY($1::text[]) OR lower(e.slug) = ANY($2::text[])`,
        [internalIds, slugs],
      );
      await client.query('ROLLBACK');
      for (const row of result.rows) {
        byId.set(row.eventId, row);
        if (row.slug) bySlug.set(row.slug, row);
      }
    } finally {
      client.release();
    }

    const pageSlugById = await resolveEventPageSlugsForEventIds([...byId.keys()], pool);

    // Events linked to ANY EventPage (draft or published) are group members: their
    // legacy URL will 301 once the page publishes, so never 410 them prematurely.
    const anyPageLinked = new Set();
    const pageLinks = await pool.query(`SELECT DISTINCT link."eventId" AS "eventId" FROM "EventPageEvent" link`);
    for (const row of pageLinks.rows) anyPageLinked.add(row.eventId);

    const entriesBySource = new Map();
    const unmatched = [];
    const kept = [];
    for (const rec of records) {
      const idn = rec.identity;
      const row = byId.get(idn.internalId) || bySlug.get(idn.slug);
      if (!row) { unmatched.push(idn.slug); continue; }
      const sourcePath = rec.pathname;
      const canonical = pageSlugById.get(row.eventId);
      if (!canonical) {
        if (anyPageLinked.has(row.eventId)) {
          kept.push({ slug: idn.slug, reason: 'linked to an EventPage (not yet published)' });
        } else if (Number(row.futureSessionCount) === 0) {
          entriesBySource.set(sourcePath, { sourcePath, eventId: row.eventId, kind: 'past_slot', status: 410, targetPath: null });
        } else {
          kept.push({ slug: idn.slug, reason: 'no canonical EventPage, has future sessions' });
        }
        continue;
      }
      const targetPath = `/events/${canonical}`;
      if (targetPath === sourcePath) { kept.push({ slug: idn.slug, reason: 'already the canonical URL' }); continue; }
      entriesBySource.set(sourcePath, { sourcePath, eventId: row.eventId, kind: idn.kind, status: 301, targetPath });
    }

    const map = {
      version: 1,
      generatedAt: new Date().toISOString(),
      entries: [...entriesBySource.values()].sort((a, b) => a.sourcePath.localeCompare(b.sourcePath)),
    };
    const errors = validateEventRedirectMap(map);
    const summary = {
      inputUrls: paths.length,
      nonEventCount: nonEventPaths.length,
      matched301: map.entries.filter((e) => e.status === 301).length,
      matched410: map.entries.filter((e) => e.status === 410).length,
      keptLiveFallback: kept.length,
      unmatched: unmatched.length,
      validationErrors: errors,
      mode: apply ? 'apply' : 'dry-run',
      outputPath,
    };

    if (errors.length) {
      console.log(JSON.stringify(summary, null, 2));
      console.error('Generated map failed validation; nothing written.');
      process.exitCode = 1;
      return;
    }
    if (apply) {
      await writeMergedMap(map, outputPath);
    }
    console.log(JSON.stringify({ ...summary, preview: map.entries.slice(0, 5) }, null, 2));
    if (!apply) console.warn(`Dry-run: no write. Re-run with --apply to write ${outputPath}.`);
    if (unmatched.length) console.warn(`Unmatched (no catalog row, NOT redirected): ${unmatched.slice(0, 10).join(', ')}${unmatched.length > 10 ? ' …' : ''}`);
    if (nonEventPaths.length) console.warn(`Non-event URLS (venues/locations/cities/places - separate workstream): ${nonEventPaths.slice(0, 10).join(', ')}${nonEventPaths.length > 10 ? ' …' : ''}`);
  } finally {
    await pool.end();
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error); process.exitCode = 1; });
}