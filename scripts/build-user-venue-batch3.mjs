function short(text) {
  const clean = String(text || '').replace(/\s+/g, ' ').trim();
  const dot = clean.indexOf('. ');
  if (dot > 40 && dot < 240) return clean.slice(0, dot + 1);
  return clean.length <= 240 ? clean : `${clean.slice(0, 237).trim()}…`;
}

