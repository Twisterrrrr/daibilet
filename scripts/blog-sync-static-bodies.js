#!/usr/bin/env node
/**
 * Синхронизирует content/blog/*.md → apps/web/src/data/blog-article-bodies.ts
 * (fallback SSR, если Article в БД недоступен).
 *
 * Usage: node scripts/blog-sync-static-bodies.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadBlogMarkdownDir } from './lib/blog-content.mjs';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = path.join(rootDir, 'content', 'blog');
const outFile = path.join(rootDir, 'apps', 'web', 'src', 'data', 'blog-article-bodies.ts');

const articles = loadBlogMarkdownDir(contentDir);
const lines = [
  '/** Autogenerated by scripts/blog-sync-static-bodies.js - do not edit by hand. */',
  'export const BLOG_ARTICLE_BODIES: Record<string, string> = {',
];

for (const article of articles) {
  const body = String(article.body || '').replace(/\r\n/g, '\n');
  const escaped = JSON.stringify(body);
  lines.push(`  ${JSON.stringify(article.slug)}: ${escaped},`);
}

lines.push('};', '');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`blog-sync-static-bodies: ${articles.length} article(s) → ${path.relative(rootDir, outFile)}`);
