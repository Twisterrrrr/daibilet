function esc(value) {
  return String(value ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r?\n/g, ' ');
}

function numOrNull(value) {
  if (value == null || value === '') return 'null';
  const n = Number(value);
  return Number.isFinite(n) ? String(n) : 'null';
}

function main() {
  const pack = JSON.parse(fs.readFileSync(PACK, 'utf8'));
  if (!Array.isArray(pack) || pack.length === 0) {
    throw new Error(`Empty monuments pack: ${PACK}`);
  }

  const byCity = {};
  for (const item of pack) {
    const cityKey = item.cityKey;
    if (!cityKey) continue;
    const filter = CREATIVE_SLUGS.has(item.slug) ? 'creative' : 'monument';
    const desc = item.shortDescription || item.hookFact || item.description || '';
    (byCity[cityKey] ||= []).push({
      name: item.title,
      desc,
      address: item.address || null,
      locationSlug: item.slug,
      mustSeeFilter: filter,
      visitMinutes: 15,
      latitude: item.latitude ?? null,
      longitude: item.longitude ?? null,
    });
  }

  const cityBlocks = Object.keys(byCity)
    .sort()
    .map((cityKey) => {
      const rows = byCity[cityKey]
        .map((row) => {
          const address =
            row.address == null ? 'null' : `'${esc(row.address)}'`;
          return `    {
      name: '${esc(row.name)}',
      desc: '${esc(row.desc)}',
      address: ${address},
      locationSlug: '${esc(row.locationSlug)}',
      mustSeeFilter: '${row.mustSeeFilter}',
      visitMinutes: ${row.visitMinutes ?? 15},
      latitude: ${numOrNull(row.latitude)},
      longitude: ${numOrNull(row.longitude)},
    }`;
        })
        .join(',\n');
      return `  '${cityKey}': [\n${rows},\n  ]`;
    })
    .join(',\n');

  const body = `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/generate-city-monuments-must-see.js
 * Source: scripts/data/catalog-monuments-2026-08-13.json
 * Do not edit by hand - re-run the generator.
 *
 * Merged into CITY_INFO.mustSee at module load so city hubs + My Day
 * «Главные места» stay curated; pack statues go to «Памятники» (+ visitMinutes 15).
 */

export type MonumentMustSeeItem = {
  name: string;
  desc: string;
  address?: string | null;
  locationSlug: string;
  mustSeeFilter: 'main' | 'monument' | 'creative';
  visitMinutes?: number;
  latitude?: number | null;
  longitude?: number | null;
};

export const CITY_MONUMENTS_MUST_SEE: Record<string, MonumentMustSeeItem[]> = {
${cityBlocks},
};

function placeKey(place: {
  locationSlug?: string | null;
  venueSlug?: string | null;
  href?: string | null;
  name?: string | null;
}): string {
  return String(place.locationSlug || place.venueSlug || place.href || place.name || '')
    .trim()
    .toLowerCase();
}

/** Append pack monuments missing from curated mustSee (skip duplicate slugs/names). */
export function mergeMonumentMustSeeIntoCityInfo(
  cityInfo: Record<string, { mustSee?: Array<Record<string, unknown>> }>,
): void {
  for (const [cityKey, extras] of Object.entries(CITY_MONUMENTS_MUST_SEE)) {
    const entry = cityInfo[cityKey];
    if (!entry?.mustSee || !extras.length) continue;
    const seen = new Set(
      entry.mustSee
        .map((place) =>
          placeKey({
            locationSlug: place.locationSlug as string | undefined,
            venueSlug: place.venueSlug as string | undefined,
            href: place.href as string | undefined,
            name: place.name as string | undefined,
          }),
        )
        .filter(Boolean),
    );
    for (const extra of extras) {
      const key = placeKey(extra);
      if (!key || seen.has(key)) continue;
      entry.mustSee.push({ ...extra });
      seen.add(key);
    }
  }
}
`;

  const targets = [
    path.join(ROOT, 'apps/web/src/lib/city-monuments-must-see.ts'),
    path.join(ROOT, 'apps/public/src/lib/city-monuments-must-see.ts'),
  ];
  for (const target of targets) {
    fs.writeFileSync(target, body, 'utf8');
    console.log('wrote', path.relative(ROOT, target), 'cities', Object.keys(byCity).length, 'items', pack.length);
  }
}

main();
