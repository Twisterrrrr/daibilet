function slugify(value) {
  const map = {
    а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
    и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
    с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sch',
    ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
  };
  return String(value || '')
    .toLowerCase()
    .split('')
    .map((char) => map[char] ?? char)
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-{2,}/g, '-')
    .slice(0, 72);
}

function dash(text) {
  return String(text || '')
    .replace(/\u2014|\u2013|\u2212/g, '-')
    .replace(/\s+-\s+/g, ' - ');
}

function row(cityKey, title, short, hook, desc, address, lat, lng, extra = {}) {
  return {
    slug: extra.slug || `${cityKey}-${slugify(title)}`,
    cityKey,
    title: dash(title),
    shortDescription: dash(short),
    hookFact: dash(hook),
    description: dash(desc),
    wayToFind: dash(extra.wayToFind || `Ориентир: ${address}.`),
    latitude: lat,
    longitude: lng,
    address: dash(address),
    metroStation: extra.metroStation ?? null,
    kind: extra.kind || 'MONUMENT',
    familyHint: extra.familyHint || 'location',
  };
}

