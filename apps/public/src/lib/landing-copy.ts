export function resolveLandingCopy(slug: string): LandingCopyEntry | null {
  const key = canonicalLandingSlug(slug);
  return LANDING_COPY[key] || null;
}

export type LandingProfileKind = 'bus' | 'river' | 'dinner' | 'seasonal' | 'bridges' | 'default';

/** Показывать editorial-тексты подборки вместо city-guide или seasonal intro. */
export function shouldUseLandingCopy(slug: string, profile: LandingProfileKind, citySlug?: string): boolean {
  if (!resolveLandingCopy(slug)) return false;
  if (profile === 'seasonal') return false;
  if (profile === 'bridges') return false;
  if (profile === 'bus' || profile === 'river') return !citySlug;
  return true;
}
