/** Подбор популярных рейсов на лендинге - порядок отображения. */
export const BRIDGES_POPULAR_MATCHERS: Array<(title: string) => boolean> = [
  (title) => /пять\s+разводных\s+мостов/i.test(title) || /5\s+разводных/i.test(title),
  (title) => /огни залива/i.test(title) && /жив/i.test(title),
  (title) => /дискотека/i.test(title) && /адмиралтей/i.test(title),
  (title) => /три\s+разводных\s+моста/i.test(title) && /петроград/i.test(title),
];

