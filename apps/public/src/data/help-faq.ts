export function helpFaqJsonLd() {
  const allFaqs = HELP_FAQ_CATEGORIES.flatMap((category) => category.items);
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: allFaqs.map((item) => ({
      '@type': 'Question',
      name: item.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.a,
      },
    })),
  };
}
