export const RIVER_SLUG_ALIASES: Record<string, string> = {
  msk: 'moscow',
  moscow: 'moscow',
  spb: 'spb',
  'saint-petersburg': 'spb',
  rostov: 'rostov-on-don',
  'rostov-on-don': 'rostov-on-don',
};

export function riverCityGuide(cityName: string | null): RiverCityGuide | null {
  if (!cityName) return null;
  return RIVER_CITY_GUIDES[cityName] || null;
}

export function riverCityGuideBySlug(citySlug?: string | null): RiverCityGuide | null {
  const key = String(citySlug || '').trim().toLowerCase();
  if (!key) return null;
  const normalized = RIVER_SLUG_ALIASES[key] || key;
  return Object.values(RIVER_CITY_GUIDES).find((guide) => guide.slug === normalized) || null;
}

export function riverLandingRoot(slug: string) {
  const key = slug.toLowerCase();
  if (key.includes('bridge')) return '/landings/bridges-night';
  if (key.includes('party') || key === 'party-boat' || key === 'river-disco' || key === 'boat-party') {
    return '/landings/river-party';
  }
  return `/landings/river-cruises`;
}
