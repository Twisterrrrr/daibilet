export function getSeasonalLanding(slug: string): SeasonalLandingMeta | null {
  const key = String(slug || '').trim().toLowerCase();
  return SEASONAL_LANDINGS[key] || null;
}

export function seasonalCityGuide(landingSlug: string, cityName: string | null): SeasonalCityGuide | null {
  const landing = getSeasonalLanding(landingSlug);
  if (!landing || !cityName) return null;
  return landing.cities[cityName] || null;
}

export function seasonalCityGuideBySlug(landingSlug: string, citySlug?: string | null): SeasonalCityGuide | null {
  const landing = getSeasonalLanding(landingSlug);
  if (!landing || !citySlug) return null;
  const key = citySlug.trim().toLowerCase();
  return Object.values(landing.cities).find((guide) => guide.slug === key) || null;
}

export function seasonalLandingRoot(slug: string) {
  return landingCategoryHref(slug);
}
