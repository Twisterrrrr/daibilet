export function resolveLandingContentPack(slug: string): LandingContentPack | null {
  const key = String(slug || '')
    .trim()
    .toLowerCase()
    .replace(/_/g, '-');
  if (LANDING_CONTENT_PACKS[key]) return LANDING_CONTENT_PACKS[key];
  if (key.includes('bridge') || key === 'night-bridges') return LANDING_CONTENT_PACKS['bridges-night'];
  return null;
}

export function landingContentPackSlugs(): string[] {
  return Object.keys(LANDING_CONTENT_PACKS);
}
